"""Google Colab notebook generation for remote model merging."""

from __future__ import annotations

import json
from pathlib import Path


def generate_colab_notebook(
    name: str,
    config_yaml: str,
    output_path: Path | str | None = None,
) -> Path:
    """Generate a complete, ready-to-run Google Colab Jupyter Notebook (.ipynb)."""
    target_path = (
        Path(output_path) if output_path else Path.cwd() / "merges" / name / f"merge_{name}.ipynb"
    )
    target_path.parent.mkdir(parents=True, exist_ok=True)

    escaped_yaml = config_yaml.replace('"""', r"\"\"\"")

    cells = [
        {
            "cell_type": "markdown",
            "metadata": {},
            "source": [
                f"# Merge Model: `{name}`\n",
                "\n",
                "Generated by [Lathe](https://github.com/lathe-agent/lathe). "
                "This notebook executes model merging with `mergekit` in the cloud "
                "with GPU/high-RAM acceleration, then uploads the merged safetensors "
                "directly to Hugging Face.\n",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 1. Install mergekit and huggingface_hub\n",
                "!pip install -q mergekit huggingface_hub\n",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 2. Authenticate with Hugging Face\n",
                "from huggingface_hub import login\n\n",
                "login()\n",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 3. Write mergekit configuration\n",
                f'config_yaml = """{escaped_yaml}"""\n\n',
                'with open("config.yaml", "w", encoding="utf-8") as f:\n',
                "    f.write(config_yaml)\n\n",
                'print("Generated config.yaml successfully.")\n',
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 4. Run mergekit with lazy loading & low-memory flags\n",
                "!mergekit-yaml config.yaml ./merged "
                "--lazy-unpickle --allow-crimes --low-cpu-memory --copy-tokenizer\n",
            ],
        },
        {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": [
                "# 5. Upload merged model weights and tokenizer to Hugging Face\n",
                "from huggingface_hub import HfApi\n\n",
                "api = HfApi()\n",
                f'prompt_msg = "Enter destination HF repo id (e.g. username/{name}): "\\n',
                "repo_id = input(prompt_msg).strip()\n",
                "if repo_id:\n",
                "    api.create_repo(repo_id=repo_id, exist_ok=True, private=True)\n",
                "    api.upload_folder(\n",
                '        folder_path="./merged",\n',
                "        repo_id=repo_id,\n",
                f'        commit_message="Upload merged model {name} generated via Lathe",\n',
                "    )\n",
                '    print(f"Uploaded successfully to https://huggingface.co/{repo_id}")\n',
                "else:\n",
                '    print("No destination repo ID provided; skipping push.")\n',
            ],
        },
    ]

    notebook_data = {
        "cells": cells,
        "metadata": {
            "accelerator": "GPU",
            "colab": {
                "name": f"Merge {name}",
                "provenance": [],
            },
            "language_info": {
                "name": "python",
                "version": "3.10",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 2,
    }

    target_path.write_text(json.dumps(notebook_data, indent=2), encoding="utf-8")
    return target_path
